/**
 * Normal verification entry (192 Phase 3 wiring): runs the ordinary rule
 * engine exactly as before, then — when meta carries an ACTIVE running
 * design-review context — produces the trusted domain outcome from the
 * canonical snapshot. A `verify.require=false`, a config-error skip, or a
 * verify override may relax ORDINARY rules but can NEVER skip or replace
 * the trusted domain contract (acceptance: skip cannot fabricate PASS).
 */
export async function runVerification(
  config: PipelineConfig,
  meta: SessionMeta,
  assistantMessages: string[],
  options?: RunVerificationOptions,
): Promise<VerificationRunResult> {
  // 194 Phase 1: the context is derived ONCE and the snapshot set captures
  // every consumed deliverable exactly once (review: report; update: plan +
  // consumed report + standalone receipt). The same bytes are shared with the
  // groups/flat rule engine through an exact-path lookup — no double-read
  // window in which the domain verdict and a rule judge different content.
  const ctx = deriveDomainVerificationContext(meta);
  const capture = ctx ? await captureDesignReviewSnapshots(ctx) : undefined;
  const baseOptions: RunVerificationOptions | undefined = capture
    ? {
        ...options,
        snapshotLookup: options?.snapshotLookup
          ? (p: string) => options.snapshotLookup!(p) ?? capture.lookup(p)
          : capture.lookup,
      }
    : options;
  const base = await runVerificationBase(config, meta, assistantMessages, baseOptions);
  const designReviewOutcome = ctx
    ? await computeDesignReviewDomainOutcome(config, meta, ctx, capture)
    : undefined;
  if (!designReviewOutcome) return base;
  return { ...base, designReviewOutcome };
}

/**
 * 192 Phase 3 / 194 Phase 1: trusted domain outcome over the CURRENT running
 * context. Purely read-only: no meta writes, no dispatch, no stage changes —
 * the owner consumer decides transitions.
 */
async function computeDesignReviewDomainOutcome(
  config: PipelineConfig,
  meta: SessionMeta,
  ctx: TrustedDomainVerificationContext,
  capture?: DesignReviewSnapshotSet,
): Promise<DesignReviewVerificationOutcome | undefined> {
  const state = meta.designReview!;
  const operation = state.operation!;

  if (ctx.kind === "review") {
    // Prefer the shared capture (ONE snapshot for domain + groups).
    let content: string | undefined = capture?.lookup(ctx.reportPath);
    if (content === undefined) {
      try {
        content = await fs.readFile(ctx.reportPath, "utf-8");
      } catch (err) {
        const detail = err instanceof Error ? err.message : String(err);
        return {
          kind: "invalid",
          failures: [{ ruleType: "designReviewReport", detail: `current report snapshot unreadable: ${ctx.reportPath} (${detail})`, timestamp: Date.now() }],
        };
      }
    }
    // Contract anchors (single source): verdict/issue shapes are DECLARED in
    // the deployed verify.md; unusable anchors fall back to built-in defaults
    // mirroring the shipped template. Invalid regex is fail-closed downstream.
    const anchors = await loadVerifyContractAnchors(config, "design-review");
    // 193 Phase 1 (task 6): the confirmation mode governing THIS run is
    // resolved once (operation-pinned first) and drives the smart decision
    // gate over the SAME snapshot; the decision is handed to consumers
    // through this outcome so the coordinator never re-reads the report.
    const reviewConfirmMode = resolveDesignReviewConfirmMode(meta, config);
    const v = verifyDesignReviewReportSnapshot(content, {
      pipelineId: ctx.pipelineId,
      planDoc: ctx.planDoc,
      round: ctx.round,
      operationId: ctx.operationId,
      inputHash: ctx.inputHash,
    }, {
      verdictPatterns: anchors.anchors.verdict?.patterns,
      issueHeadingPattern: anchors.anchors.issueHeading?.patterns[0],
      smartDecisionMode: reviewConfirmMode === "smart",
    });
    if (v.verdict === "invalid") {
      return {
        kind: "invalid",
        failures: v.failures.map((detail) => ({ ruleType: "designReviewReport", detail, timestamp: Date.now() })),
      };
    }
    const identity = buildDesignReviewIdentity(meta, state, operation);
    if (!identity) {
      return { kind: "invalid", failures: [{ ruleType: "designReviewReport", detail: "current review identity is unresolvable", timestamp: Date.now() }] };
    }
    return {
      kind: "report",
      verdict: v.verdict,
      identity,
      planHash: state.planHash ?? "",
      reportHash: v.reportHash,
      issues: v.issues,
      // 193 Phase 1: smart plan-revision decision verified from the SAME
      // reportHash snapshot (present only on a valid FAIL under smart mode).
      ...(v.verdict === "fail" && v.smartDecision !== undefined ? { smartDecision: v.smartDecision } : {}),
    };
  }

  // kind === "update" — 194 Phase 1: ONE snapshot set supplies the plan bytes,
  // the consumed report bytes and (standalone only) the receipt bytes. Building
  // the validator input from that set is the single place where the OUTPUT
  // binding is interpreted, so "missing receipt" can never degrade into
  // "back-fill the receipt from the plan body".
  const set = capture ?? (await captureDesignReviewSnapshots(ctx));
  const evaluated = evaluateUpdateSnapshots(ctx, set);
  if (!evaluated.ok) {
    return {
      kind: "invalid",
      failures: evaluated.failures.map((detail) => ({ ruleType: "designReviewUpdate", detail, timestamp: Date.now() })),
    };
  }
  // 192 issue 8: the consumed-report snapshot handed to the validator is the
  // SAME bytes the capture bound inputs to (no second file read), so report
  // attribution (snapshot hash vs receipt reportHash + declared **operation**
  // vs the consumed review identity) is enforced inside the evaluator.
  const verdict = validateDesignReviewUpdate(evaluated.input);
  if (verdict.status === "invalid") {
    return {
      kind: "invalid",
      failures: verdict.failures.map((detail) => ({ ruleType: "designReviewUpdate", detail, timestamp: Date.now() })),
    };
  }
  if (verdict.status === "paused") {
    return { kind: "paused", reason: verdict.reason };
  }
  const identity = buildDesignReviewIdentity(meta, state, operation);
  if (!identity) {
    return { kind: "invalid", failures: [{ ruleType: "designReviewUpdate", detail: "current update identity is unresolvable", timestamp: Date.now() }] };
  }
  return {
    kind: "update",
    status: "ready",
    identity,
    reportHash: ctx.reportHash,
    baselinePlanHash: ctx.baselinePlanHash,
    newPlanHash: verdict.newPlanHash,
    // 194 C2: the plan hash alone no longer describes the update's output —
    // the standalone receipt hash rides along for pre-advance revalidation.
    ...(verdict.receiptHash !== undefined ? { receiptHash: verdict.receiptHash } : {}),
  };
}

async function runVerificationBase(
  config: PipelineConfig,
  meta: SessionMeta,
  assistantMessages: string[],
  options?: RunVerificationOptions,
): Promise<VerificationRunResult> {
  const stageConfig = config.stages[meta.currentStage];
  const verifyConfig = stageConfig.verify;

  if (!verifyConfig || !verifyConfig.require) {
    return {
      rulePassed: true,
      ruleMissing: [],
    };
  }

  // Override from options takes precedence over stage config.
  // Path resolution is a single source (resolveVerifyFilePath) shared with the
  // contract loader (Phase 2 / 176, DRY).
  const verifyPath = resolveVerifyFilePath(config, meta.currentStage, options?.verifyFile);

  // 148 Phase 2: diagnose verify.md config AFTER parsing (M4 fix).
  // Previously diagnose ran before parseVerifyFile causing:
  // - double fs.readFile + parseFrontmatter (performance)
  // - TOCTOU window between diagnose and parse (correctness)
  // Now parse first, then diagnose — single-read path (see raw content reuse below).
  const { rules, parseError } = await parseVerifyFile(verifyPath);

  // M4 fix: diagnose using the same file. When parseVerifyFile has already read
  // the file, we still call diagnoseVerifyConfig (which re-reads — acceptable
  // for small config files). The key fix is ordering: diagnose AFTER parse
  // eliminates the TOCTOU window.
  const diagnosis = await diagnoseVerifyConfig(verifyPath);
  if (!diagnosis.ok) {
    return {
      rulePassed: false,
      ruleMissing: [],
      skipped: true,
      configErrors: diagnosis.errors.map(e => e.detail),
    };
  }

  // Build audit log closure: injects pipelineId into every error-level audit entry
  const logError: AuditLogFn = options?.logError ??
    ((stage, msg) => safeWriteAuditLog(stage, { pipelineId: meta.pipelineId, ...msg }, "error"));

  // Default structured result when no structured rules exist
  let structuredResult: StructuredVerifyResult = { passed: true, failures: [] };

  // Phase 9: compute rule set identity fields
  const rulesSource = path.relative(config.projectRoot, verifyPath);
  const rulesParsed = rules !== null;
  const selfVerifySkip = verifyConfig.selfVerifySkip === true;

  // Task 3: When parse fails, write verify_config_skip audit event
  if (!rules && parseError) {
    await safeWriteAuditLog("verify_config_skip", {
      pipelineId: meta.pipelineId,
      stage: meta.currentStage,
      reason: parseError,
      rulesSource,
    });
  }

  if (!rules) {
    // No rules defined — structured-only path, no LLM fallback (Q6-B)
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };

    return {
      rulePassed: false,
      ruleMissing: [],
      verifyResult,
      rulesSource,
      rulesParsed,
      selfVerifySkip,
      parseError,
    };
  }

  // Resolve {requirementDoc} placeholders in rule paths using session metadata
  let resolvedRules = resolvePlaceholders(rules, meta);

  // Replace plan doc glob with concrete path (only for plan stage)
  resolvedRules = await applyConcreteStageDocPaths(resolvedRules, config, meta);

  // Defer content-pattern rules that match the caller's deferContentPatterns list.
  // This is a per-execution skip — does not touch verify.md or hasCustom state.
  // Used by confirm gate to prevent the plan marker rule from blocking verification
  // when the marker will be written later by the confirm gate (C2 ordering fix).
  //
  // Glob-aware matching: `applyConcreteStageDocPaths` above replaces plan doc globs
  // (e.g. `docs/design/*_Plan.md`) with the concrete relative path (e.g.
  // `docs/design/162_Confirm_Plan.md`). The caller's defer entries may still use the
  // glob form. We resolve globs in the defer list using the same concrete path
  // derivation so that pattern equality comparison works on both glob and non-glob inputs.
  const deferList = options?.deferContentPatterns;
  let deferredCount = 0;
  if (deferList && deferList.length > 0) {
    // Resolve plan doc globs in defer entries so they match resolvedRules paths
    let resolvedDeferList = deferList;
    if (meta.currentStage === "plan") {
      const planDocPath = await resolvePlanDocPath(config, meta);
      if (planDocPath) {
        const relPlanDoc = path.relative(config.projectRoot, planDocPath);
        resolvedDeferList = deferList.map((d) => ({
          ...d,
          path: isPlanDocGlob(d.path) ? relPlanDoc : d.path,
        }));
      }
    }

    const matchesDefer = (rulePath: string, pattern: string): boolean =>
      resolvedDeferList.some((d) => d.path === rulePath && d.pattern === pattern);

    // Flat fileContentPattern (legacy path) — behavior unchanged.
    if (resolvedRules.fileContentPattern) {
      const original = resolvedRules.fileContentPattern;
      const filtered = original.filter((r) => !matchesDefer(r.path, r.pattern));
      deferredCount += original.length - filtered.length;
      if (filtered.length !== original.length) {
        resolvedRules = { ...resolvedRules, fileContentPattern: filtered };
      }
    }

    // Phase 1 / 176: penetrate groups — remove matching patterns from nodes;
    // drop emptied nodes; keep emptied groups (always-pass semantics).
    if (resolvedRules.groups) {
      const nextGroups = resolvedRules.groups.map((group) => ({
        ...group,
        rules: group.rules
          .map((node): VerifyGroupRuleNode | null => {
            if (!node.patterns || node.patterns.length === 0) return node;
            const effectivePath = node.path ?? resolvedRules.path ?? "";
            const kept = node.patterns.filter((p) => !matchesDefer(effectivePath, p));
            deferredCount += node.patterns.length - kept.length;
            if (kept.length === 0) return null;
            return { ...node, patterns: kept };
          })
          .filter((node): node is VerifyGroupRuleNode => node !== null),
      }));
      resolvedRules = { ...resolvedRules, groups: nextGroups };
    }

    if (deferredCount > 0) {
      await safeWriteAuditLog("verify_rule_deferred", {
        pipelineId: meta.pipelineId,
        stage: meta.currentStage,
        deferredCount: String(deferredCount),
      }, "info");
    }
  }

  // Detect unresolved {requirementDoc} placeholders (L2-A: explicit failure instead of EISDIR)
  const unresolvedPlaceholder = /\{requirementDoc\}/;
  const groupsContainPlaceholder = (re: RegExp): boolean =>
    !!resolvedRules.groups?.some((group) =>
      (group.when !== undefined && re.test(group.when)) ||
      (resolvedRules.path !== undefined && re.test(resolvedRules.path)) ||
      group.rules.some((node) =>
        (node.path !== undefined && re.test(node.path)) ||
        (node.patterns?.some((p) => re.test(p)) ?? false),
      ),
    );
  const unresolvedRuleType =
    (resolvedRules.requiredFiles?.some(p => unresolvedPlaceholder.test(p)) ? "requiredFiles" : null) ??
    (resolvedRules.fileContentPattern?.some(r => unresolvedPlaceholder.test(r.path)) ? "fileContentPattern" : null) ??
    (resolvedRules.path && unresolvedPlaceholder.test(resolvedRules.path) ? "fileContentPattern" : null) ??
    (groupsContainPlaceholder(unresolvedPlaceholder) ? "fileContentPattern" : null);
  if (unresolvedRuleType) {
    const structuredResult: StructuredVerifyResult = {
      passed: false,
      failures: [{
        ruleType: unresolvedRuleType,
        // Phase 4 (Bug 4-A): append remediation hint — run /pipeline-start with doc_file
        detail: `requirementDoc not set, cannot resolve {requirementDoc} verify rule path. Run /pipeline-start <doc_file> to set requirementDoc`,
      }],
    };
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };
    return {
      rulePassed: false,
      ruleMissing: [],
      structuredResult,
      verifyResult,
    };
  }

  // Detect unresolved {pipelineId} placeholder — symmetric guard with requirementDoc.
  // When pipelineId is missing, the verify rule pattern would otherwise fail with
  // a cryptic "pattern not found" error instead of a clear remediation message.
  const unresolvedPipelineId = /\{pipelineId\}/;
  const unresolvedPipelineIdRuleType =
    (resolvedRules.requiredFiles?.some(p => unresolvedPipelineId.test(p)) ? "requiredFiles" : null) ??
    (resolvedRules.fileContentPattern?.some(r => unresolvedPipelineId.test(r.path) || unresolvedPipelineId.test(r.pattern)) ? "fileContentPattern" : null) ??
    (resolvedRules.path && unresolvedPipelineId.test(resolvedRules.path) ? "fileContentPattern" : null) ??
    (groupsContainPlaceholder(unresolvedPipelineId) ? "fileContentPattern" : null);
  if (unresolvedPipelineIdRuleType) {
    const structuredResult: StructuredVerifyResult = {
      passed: false,
      failures: [{
        ruleType: unresolvedPipelineIdRuleType,
        detail: `pipelineId not set, cannot resolve {pipelineId} verify rule. Run /pipeline-start to initialize a pipeline and generate pipelineId`,
      }],
    };
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };
    return {
      rulePassed: false,
      ruleMissing: [],
      structuredResult,
      verifyResult,
    };
  }

  // 192 Phase 3 (task 4, issue-2 fix): fail-closed identity-placeholder guard
  // for design-review. Identity patterns are substituted from the AUTHORITATIVE
  // narrowed meta state (see substituteDesignReviewIdentityPlaceholders); a
  // leftover {planDoc}/{round}/{operationId}/{inputHash} means the state cannot
  // provide that value — explicit verification failure (missing contract →
  // invalid), never a silently-matching-as-literal non-match.
  if (meta.currentStage === "design-review" && meta.designReview) {
    const unresolvedDr = /\{(?:planDoc|round|operationId|inputHash)\}/;
    const drPlaceholderHit =
      (resolvedRules.requiredFiles?.some((p) => unresolvedDr.test(p)) ? "requiredFiles" : null) ??
      (resolvedRules.fileContentPattern?.some((r) => unresolvedDr.test(r.pattern) || unresolvedDr.test(r.path)) ? "fileContentPattern" : null) ??
      (resolvedRules.groups?.some((g) =>
        (g.when !== undefined && unresolvedDr.test(g.when)) ||
        g.rules.some((n) =>
          (n.path !== undefined && unresolvedDr.test(n.path)) ||
          (n.patterns?.some((p) => unresolvedDr.test(p)) ?? false),
        ),
      ) ? "fileContentPattern" : null);
    if (drPlaceholderHit) {
      const structuredResult: StructuredVerifyResult = {
        passed: false,
        failures: [{
          ruleType: drPlaceholderHit,
          detail: "design-review identity placeholder unresolvable from authoritative session state (fail-closed)",
        }],
      };
      const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };
      return {
        rulePassed: false,
        ruleMissing: [],
        structuredResult,
        verifyResult,
        rulesSource,
        rulesParsed,
        selfVerifySkip,
      };
    }
  }

  // Check if any structured (non-keyword) rules are defined
  const hasStructuredRules =
    (resolvedRules.requiredFiles && resolvedRules.requiredFiles.length > 0) ||
    (resolvedRules.requiredCommands && resolvedRules.requiredCommands.length > 0) ||
    !!resolvedRules.requiredGit ||
    (resolvedRules.fileContentPattern && resolvedRules.fileContentPattern.length > 0) ||
    (resolvedRules.groups && resolvedRules.groups.length > 0);

  if (hasStructuredRules) {
    // Phase 6 (139): merge VERIFIED_COMMANDS from task result text with toolCallRecords
    const verifiedCmds = parseVerifiedCommands(assistantMessages);
    const mergedRecords = [
      ...(options?.toolCallRecords ?? []),
      ...verifiedCmds,
    ];

    // Use the structured rule engine
    structuredResult = await executeStructuredRules(
      resolvedRules,
      config.projectRoot,
      assistantMessages,
      options?.execFn,
      logError,
      mergedRecords.length > 0 ? mergedRecords : undefined,
      verifyConfig.selfVerifySkip === true,
      meta.stageStartTime,
      meta.currentStage,
      // 192 Phase 3 (task 4): shared exact-path snapshot for groups/flat rules
      options?.snapshotLookup,
      rulesSource,
    );
  } else {
    // Legacy path: keyword-only rules
    const ruleResult = ruleVerify(resolvedRules, assistantMessages);
    if (!ruleResult.passed) {
      structuredResult = {
        passed: false,
        failures: [{ ruleType: "keywords", detail: `Missing keywords: ${ruleResult.missing.join(", ")}` }],
      };
    }
  }

  // Combine results: structured-only path (Q6-B: LLM layer removed)
  const overallPassed = structuredResult.passed;
  const verifyResult: VerifyResult = { structured: structuredResult, overallPassed };

  if (overallPassed) {
    return {
      rulePassed: true,
      ruleMissing: [],
      structuredResult,
      verifyResult,
      rulesSource,
      rulesParsed,
      selfVerifySkip,
    };
  }

  // Collect missing keyword info for backward compat
  const keywordFailures = structuredResult.failures.filter(f => f.ruleType === "keywords");
  const ruleMissing = keywordFailures.length > 0
    ? resolvedRules.keywords.filter(kw => !assistantMessages.join("\n").includes(kw))
    : [];

  return {
    rulePassed: false,
    ruleMissing,
    structuredResult,
    verifyResult,
    rulesSource,
    rulesParsed,
    selfVerifySkip,
  };
}

/**
 * P1: Pre-check required files before running full verification.
 * Returns early if requiredFiles are not yet produced, avoiding
 * false-negative verification failures and freeze triggers.
 *
 * @param config - Pipeline configuration
 * @param meta - Current session metadata
 * @returns Object with passed flag and missing file list
 */
export async function precheckRequiredFiles(
  config: PipelineConfig,
  meta: SessionMeta,
): Promise<{ passed: boolean; missing: string[] }> {
  const stageConfig = config.stages[meta.currentStage];
  const verifyConfig = stageConfig.verify;

  // No verify config or verify not required → precheck passes
  if (!verifyConfig || !verifyConfig.require) {
    return { passed: true, missing: [] };
  }

  const verifyPath = resolveVerifyFilePath(config, meta.currentStage);

  // Parse verify.md to extract requiredFiles rules
  const { rules, parseError } = await parseVerifyFile(verifyPath);

  // No rules → precheck passes
  if (!rules) {
    return { passed: true, missing: [] };
  }

  // Resolve {requirementDoc} placeholders before checking files
  // This ensures precheck behavior is consistent with runVerification
  let resolvedRules = resolvePlaceholders(rules, meta);

  // Replace plan doc glob with concrete path (only for plan stage)
  resolvedRules = await applyConcreteStageDocPaths(resolvedRules, config, meta);

  // Collect required file paths from both flat requiredFiles and groups.
  // Phase 0/176 fix: v6 templates place requiredFile nodes inside groups,
  // inheriting the file-level `path` when the node has no explicit path.
  const allRequiredPaths: string[] = [];

  // Flat requiredFiles (legacy templates)
  if (resolvedRules.requiredFiles && resolvedRules.requiredFiles.length > 0) {
    allRequiredPaths.push(...resolvedRules.requiredFiles);
  }

  // Groups-based requiredFile nodes (v6 templates)
  if (resolvedRules.groups) {
    for (const group of resolvedRules.groups) {
      for (const node of group.rules) {
        if (node.type === "requiredFile") {
          // Node path inherits from file-level rules.path when absent
          const effectivePath = node.path ?? resolvedRules.path;
          if (effectivePath) {
            allRequiredPaths.push(effectivePath);
          }
        }
      }
    }
  }

  // No required files found → precheck passes
  if (allRequiredPaths.length === 0) {
    return { passed: true, missing: [] };
  }

  // Check if required files exist
  const result = await verifyRequiredFiles(allRequiredPaths, config.projectRoot);

  if (result.passed) {
    return { passed: true, missing: [] };
  }

  // Extract missing files from detail message
  // verifyRequiredFiles returns detail like "Missing files: file1, file2"
  const missingMatch = result.detail.match(/Missing files:\s*(.+)/);
  const missing = missingMatch
    ? missingMatch[1].split(",").map(s => s.trim())
    : allRequiredPaths;

  return { passed: false, missing };
}

/**
 * Checks whether a line at the given index is inside a fenced code block.
 * Lightweight scan: toggles inCode state on ``` fences encountered before
 * the target line. Does not distinguish language-tagged fences.
 *
 * @param content - Full file content
 * @param lineIndex - Character offset of the line to check
 * @returns true if the line is inside a fenced code block
 */
function isInsideFencedCodeBlock(content: string, lineIndex: number): boolean {
  // Scan from start to lineIndex, counting ``` occurrences
  const before = content.substring(0, lineIndex);
  const fenceMatches = before.match(/^```/gm);
  // Odd number of fences = inside a code block
  return (fenceMatches?.length ?? 0) % 2 === 1;
}

/**
 * Prechecks whether the interactive completion marker has been written
 * to the requirement document. Returns true if the marker is found as a
 * **line-start heading** (anchored to `^` in multiline mode) and is NOT
 * inside a fenced code block.
 *
 * This fixes the 88_Feat accident where inline backtick references to the
 * marker (e.g., `` `## 模型确认` ``) triggered a false positive via
 * `content.includes(marker)`.
 *
 * Returns false (treated as "not yet complete") when:
 * - requirementDoc is not set in session meta
 * - The file cannot be read (missing, permission error, etc.)
 * - The marker is not found at any line start
 * - The marker is only found inside a fenced code block
 *
 * @param meta - Current session metadata
 * @param marker - The completion marker text to search for
 * @param projectRoot - Project root for resolving relative requirementDoc paths
 */
export async function precheckCompletionMarker(
  meta: SessionMeta,
  marker: string,
  projectRoot: string,
): Promise<boolean> {
  if (!meta.requirementDoc) {
    return false;
  }

  const docPath = path.isAbsolute(meta.requirementDoc)
    ? meta.requirementDoc
    : path.join(projectRoot, meta.requirementDoc);

  try {
    const content = await fs.readFile(docPath, "utf-8");
    // Build regex: escape marker, anchor to line start, multiline flag
    const escapedMarker = escapeRegExp(marker);
    const regex = new RegExp(`^${escapedMarker}`, "mg");
    let match: RegExpExecArray | null;
    while ((match = regex.exec(content)) !== null) {
      // If this match is outside a fenced code block, marker is present
      if (!isInsideFencedCodeBlock(content, match.index)) {
        return true;
      }
    }
    return false;
  } catch {
    return false;
  }
}

/**
 * Prechecks whether the clarify stage is in "await-answer" state.
 * Only effective for the clarify stage; returns { awaiting: false } for all other stages.
 *
 * Reads the requirement document and reuses deriveClarifyForwardArgs to determine
 * whether the latest round is waiting for a user answer. If so, verification
 * should be deferred (the user needs to write the answer in the document first).
 *
 * @param config - Pipeline configuration (used for projectRoot)
 * @param meta - Current session metadata
 * @returns Object with awaiting flag and optional round number
 */
export async function precheckClarifyAwaitAnswer(
  config: PipelineConfig,
  meta: SessionMeta,
): Promise<{ awaiting: boolean; round?: number }> {
  // Only effective for clarify stage
  if (meta.currentStage !== "clarify") {
    return { awaiting: false };
  }

  if (!meta.requirementDoc) {
    return { awaiting: false };
  }

  const docPath = path.isAbsolute(meta.requirementDoc)
    ? meta.requirementDoc
    : path.join(config.projectRoot, meta.requirementDoc);

  try {
    const content = await fs.readFile(docPath, "utf-8");

    // Phase 2 / 176: load runtime anchors from the deployed verify.md. When the
    // roundHeading anchor is unavailable, fail-open (do not defer) and audit.
    // Non-roundHeading issues are logged for audit but do NOT trigger fail-open.
    const { anchors, issues } = await loadVerifyContractAnchors(config, "clarify");
    if (!anchors.roundHeading) {
      await safeWriteAuditLog("contract_anchor_unavailable", {
        pipelineId: meta.pipelineId,
        stage: "clarify",
        missingKeys: "roundHeading",
        issues: issues.join("; "),
      }, "error");
      return { awaiting: false };
    }
    // Log non-roundHeading issues for audit without changing behavior
    if (issues.length > 0) {
      await safeWriteAuditLog("contract_anchor_issues", {
        pipelineId: meta.pipelineId,
        stage: "clarify",
        issues: issues.join("; "),
      }, "warn");
    }

    // Lazy import to avoid circular dependency at module level
    const { deriveClarifyForwardArgs } = await import("../utils/clarify-args");
    const result = deriveClarifyForwardArgs(content, anchors);
    if (result.kind === "await-answer") {
      return { awaiting: true, round: result.round };
    }
    return { awaiting: false };
  } catch {
    // Fail-open: if we can't read the doc, don't defer (proceed to verify)
    return { awaiting: false };
  }
}

