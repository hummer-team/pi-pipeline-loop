/**
 * A structured verification instruction generated by LLM parsing
 * of Markdown body content in verify.md.
 */
export interface VerificationInstruction {
  /** Type of check to perform */
  checkType: "fileExists" | "fileContent" | "command" | "gitStatus";
  /** Target of the check (file path, command, etc.) */
  target: string;
  /** Expected result (optional, depends on checkType) */
  expected?: string;
}

/**
 * Result of structured rule engine verification (Phase 1).
 */
export interface StructuredVerifyResult {
  /** Whether all structured rules passed */
  passed: boolean;
  /** List of failures with rule type and detail */
  failures: VerifyFailure[];
}

/**
 * A single rule failure detail.
 */
export interface VerifyFailure {
  /** The type of rule that failed (e.g., "requiredFiles", "requiredCommands") */
  ruleType: string;
  /** Human-readable failure detail */
  detail: string;
}

/**
 * Unified verification result from structured rules.
 * LLM verification layer removed (Q6-B) — agent-native structured verification only.
 */
export interface VerifyResult {
  /** Result from the structured rule engine */
  structured: StructuredVerifyResult;
  /** Combined overall pass: structured.passed */
  overallPassed: boolean;
}

/**
 * Result of parsing a verify.md file.
 */
export interface ParsedVerifyFile {
  /** Verification rules (null if no YAML frontmatter with keywords) */
  rules: VerifyRules | null;
  /** Model verification prompt (Markdown body or default) */
  prompt: string;
}

/**
 * Parses a verify.md file into rules and a verification prompt.
 * Expects YAML frontmatter (between --- delimiters) for keyword rules,
 * and Markdown body as the model verification prompt.
 */
export async function parseVerifyFile(
  verifyPath: string,
): Promise<ParsedVerifyFile> {
  let raw: string;
  try {
    raw = await fs.readFile(verifyPath, "utf-8");
  } catch {
    return { rules: null, prompt: DEFAULT_VERIFY_PROMPT };
  }

  const parts = raw.split(/^---\s*$/m);
  if (parts.length < 2) {
    return { rules: null, prompt: raw.trim() || DEFAULT_VERIFY_PROMPT };
  }

  // parts[0] is before first --- (should be empty/whitespace)
  // parts[1] is the YAML frontmatter content
  // parts.slice(2).join("---") is the Markdown body
  const frontmatter = parts[1].trim();
  const body = parts.slice(2).join("---").trim();

  const rules = await parseFrontmatter(frontmatter);
  const prompt = body || DEFAULT_VERIFY_PROMPT;

  return { rules, prompt };
}

/**
 * Runs rule-based verification against the aggregated assistant messages.
 * Q5 Option C: aggregates ALL assistant messages from the current stage,
 * then checks against keyword rules (AND or OR mode).
 */
export function ruleVerify(
  rules: VerifyRules,
  assistantMessages: string[],
): { passed: boolean; missing: string[] } {
  const aggregated = assistantMessages.join("\n");

  if (rules.mode === "and") {
    const missing = rules.keywords.filter(
      (kw) => !aggregated.includes(kw),
    );
    return { passed: missing.length === 0, missing };
  }

  // mode "or" — any keyword match passes
  const found = rules.keywords.some((kw) => aggregated.includes(kw));
  if (found) {
    return { passed: true, missing: [] };
  }
  return { passed: false, missing: rules.keywords };
}

/**
 * Executes all structured rules from VerifyRules against the filesystem,
 * git state, and assistant messages. Each rule type is evaluated independently.
 *
 * @param rules - The parsed verification rules from verify.md
 * @param projectRoot - Absolute path to the project root directory
 * @param assistantMessages - Aggregated assistant messages for keyword checking
 * @param execFn - Injected shell execution function
 * @param logError - Optional audit log callback for recording errors
 * @param toolCallRecords - Tool call records for selfVerifySkip matching
 * @param selfVerifySkip - Whether selfVerifySkip is enabled for this stage
 * @param stageStartTime - Stage start time for file-change invalidation
 * @returns StructuredVerifyResult with per-rule-type pass/fail and failure details
 */
export async function executeStructuredRules(
  rules: VerifyRules,
  projectRoot: string,
  assistantMessages: string[],
  execFn?: ExecFn,
  logError?: AuditLogFn,
  toolCallRecords?: Array<{ name: string; command?: string; exitCode?: number; success?: boolean; ts: number }>,
  selfVerifySkip?: boolean,
  stageStartTime?: number,
  stageName?: string,
): Promise<StructuredVerifyResult> {
  const failures: VerifyFailure[] = [];

  // 1. Required files check
  const fileResult = await verifyRequiredFiles(rules.requiredFiles, projectRoot);
  if (!fileResult.passed) {
    failures.push({ ruleType: "requiredFiles", detail: fileResult.detail });
  }

  // 2. Required commands check
  const cmdResult = await verifyRequiredCommands(
    rules.requiredCommands,
    projectRoot,
    execFn,
    logError,
    selfVerifySkip === true ? { toolCallRecords, stageStartTime, stageName } : undefined,
  );
  if (!cmdResult.passed) {
    failures.push({ ruleType: "requiredCommands", detail: cmdResult.detail });
  }

  // 3. Required git state check
  const gitResult = await verifyRequiredGit(rules.requiredGit, projectRoot, execFn, logError);
  if (!gitResult.passed) {
    failures.push({ ruleType: "requiredGit", detail: gitResult.detail });
  }

  // 4. File content pattern check
  const fcResult = await verifyFileContentPattern(rules.fileContentPattern, projectRoot, logError);
  if (!fcResult.passed) {
    failures.push({ ruleType: "fileContentPattern", detail: fcResult.detail });
  }

  // 5. Keyword check (legacy)
  if (rules.keywords.length > 0) {
    const kwResult = verifyRequiredKeywords(rules.keywords, rules.mode, assistantMessages);
    if (!kwResult.passed) {
      failures.push({ ruleType: "keywords", detail: kwResult.detail });
    }
  }

  return {
    passed: failures.length === 0,
    failures,
  };
}

/**
 * Options for structured verification within runVerification.
 */
export interface RunVerificationOptions {
  /** Dependency-injected shell execution function (replaces child_process.execSync) */
  execFn?: ExecFn;
  /** Override verify.md path; takes precedence over stage config verifyFile */
  verifyFile?: string;
  /** Optional audit log callback override (defaults to auto-constructed closure from meta.pipelineId) */
  logError?: AuditLogFn;
  /** Tool call records for selfVerifySkip (extracted from session by agent-settled) */
  toolCallRecords?: Array<{ name: string; command?: string; exitCode?: number; success?: boolean; ts: number }>;
  /**
   * Content-pattern rules to defer (skip) for this single verify execution.
   * When a rule's { path, pattern } exactly matches an entry here, the rule is
   * excluded from execution. Used by confirm gate to prevent the plan marker
   * rule from blocking verification when the marker will be written later by
   * the confirm gate (C2 ordering fix). Does NOT modify verify.md or hasCustom.
   */
  deferContentPatterns?: { path: string; pattern: string }[];
}

/**
 * Pattern to match VERIFIED_COMMANDS protocol in task result text.
 * Format: `VERIFIED_COMMANDS: cmd1,cmd2,cmd3`
 * Each command token is trimmed and non-empty entries are kept.
 */
const VERIFIED_COMMANDS_PATTERN = /^VERIFIED_COMMANDS:\s*(.+)$/m;

/**
 * A verified command record parsed from VERIFIED_COMMANDS protocol.
 * Extends the standard tool call record shape with a selfReported flag.
 */
export interface VerifiedCommandRecord {
  name: string;
  command?: string;
  exitCode?: number;
  success?: boolean;
  /**
   * Timestamp is set to 0 for self-reported commands so that the file-change
   * invalidation rule in command-verifier (matchTs comparison) always works:
   * any write/edit with ts > 0 will invalidate the self-reported match.
   * Using Date.now() would make invalidation impossible (no record can be
   * later than "now").
   */
  ts: number;
  /** True when the command was self-reported via VERIFIED_COMMANDS protocol (not from actual tool call) */
  selfReported: true;
}

/**
 * Parses VERIFIED_COMMANDS protocol lines from assistant messages.
 * Phase 6 (139): Recognizes sub-agent self-verification commands
 * reported via task result text.
 *
 * Security: ts is set to 0 (not Date.now()) so that file-change invalidation
 * in command-verifier (matchTs comparison) correctly invalidates self-reported
 * commands when any subsequent write/edit occurs in the session.
 *
 * @param messages - Array of assistant message strings
 * @returns Array of parsed command records with selfReported=true flag
 */
export function parseVerifiedCommands(
  messages: string[],
): VerifiedCommandRecord[] {
  const records: VerifiedCommandRecord[] = [];

  for (const msg of messages) {
    const match = msg.match(VERIFIED_COMMANDS_PATTERN);
    if (match && match[1]) {
      const cmds = match[1].split(",").map(c => c.trim()).filter(Boolean);
      for (const cmd of cmds) {
        records.push({
          name: "bash",
          command: cmd,
          exitCode: 0,
          success: true,
          // ts=0 ensures file-change invalidation always triggers for self-reported commands
          ts: 0,
          selfReported: true,
        });
      }
    }
  }

  return records;
}

/**
 * Runs the full verification pipeline for a stage:
 * 1. Parse verify.md
 * 2. Run structured rule verification (if new rule types present) or legacy keyword verification
 * 3. Combine structured results into a unified VerifyResult
 *
 * @param config - Pipeline configuration
 * @param meta - Session metadata
 * @param assistantMessages - Aggregated assistant messages
 * @param options - Optional LLM verification options
 */
export async function runVerification(
  config: PipelineConfig,
  meta: SessionMeta,
  assistantMessages: string[],
  options?: RunVerificationOptions,
): Promise<{
  rulePassed: boolean;
  ruleMissing: string[];
  needsModelVerify: boolean;
  modelPrompt: string;
  structuredResult?: StructuredVerifyResult;
  verifyResult?: VerifyResult;
  /** 148 Phase 2: true when verification was skipped due to config errors */
  skipped?: boolean;
  /** 148 Phase 2: human-readable config error details (present when skipped=true) */
  configErrors?: string[];
}> {
  const stageConfig = config.stages[meta.currentStage];
  const verifyConfig = stageConfig.verify;

  if (!verifyConfig || !verifyConfig.require) {
    return {
      rulePassed: true,
      ruleMissing: [],
      needsModelVerify: false,
      modelPrompt: "",
    };
  }

  // Override from options takes precedence over stage config
  const verifyFile = options?.verifyFile ?? verifyConfig.verifyFile;
  const verifyPath = verifyFile
    ? (path.isAbsolute(verifyFile)
      ? verifyFile
      : path.join(config.projectRoot, verifyFile))
    : path.join(config.projectRoot, resolveStagePath(DEFAULT_VERIFY_FILE, meta.currentStage));

  // 148 Phase 2: diagnose verify.md config AFTER parsing (M4 fix).
  // Previously diagnose ran before parseVerifyFile causing:
  // - double fs.readFile + parseFrontmatter (performance)
  // - TOCTOU window between diagnose and parse (correctness)
  // Now parse first, then diagnose — single-read path (see raw content reuse below).
  const { rules, prompt } = await parseVerifyFile(verifyPath);

  // M4 fix: diagnose using the same file. When parseVerifyFile has already read
  // the file, we still call diagnoseVerifyConfig (which re-reads — acceptable
  // for small config files). The key fix is ordering: diagnose AFTER parse
  // eliminates the TOCTOU window.
  const diagnosis = await diagnoseVerifyConfig(verifyPath);
  if (!diagnosis.ok) {
    return {
      rulePassed: false,
      ruleMissing: [],
      needsModelVerify: false,
      modelPrompt: "",
      skipped: true,
      configErrors: diagnosis.errors.map(e => e.detail),
    };
  }

  // Override modelPrompt from yml verify_{stage} when available (D5)
  // Fallback chain: yml verify_{stage} → verify.md body prompt → DEFAULT (via parseVerifyFile)
  const ymlPrompt = await getVerifyPrompt(config.projectRoot, meta.currentStage);
  const effectivePrompt = ymlPrompt ?? prompt;

  // Build audit log closure: injects pipelineId into every error-level audit entry
  const logError: AuditLogFn = options?.logError ??
    ((stage, msg) => safeWriteAuditLog(stage, { pipelineId: meta.pipelineId, ...msg }, "error"));

  // Default structured result when no structured rules exist
  let structuredResult: StructuredVerifyResult = { passed: true, failures: [] };

  if (!rules) {
    // No rules defined — structured-only path, no LLM fallback (Q6-B)
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };

    return {
      rulePassed: false,
      ruleMissing: [],
      needsModelVerify: true,
      modelPrompt: effectivePrompt,
      verifyResult,
    };
  }

  // Resolve {requirementDoc} placeholders in rule paths using session metadata
  let resolvedRules = resolvePlaceholders(rules, meta);

  // Replace plan doc glob with concrete path (only for plan stage)
  resolvedRules = await applyConcreteStageDocPaths(resolvedRules, config, meta);

  // Defer content-pattern rules that match the caller's deferContentPatterns list.
  // This is a per-execution skip — does not touch verify.md or hasCustom state.
  // Used by confirm gate to prevent the plan marker rule from blocking verification
  // when the marker will be written later by the confirm gate (C2 ordering fix).
  //
  // Glob-aware matching: `applyConcreteStageDocPaths` above replaces plan doc globs
  // (e.g. `docs/design/*_plan.md`) with the concrete relative path (e.g.
  // `docs/design/162_Confirm_plan.md`). The caller's defer entries may still use the
  // glob form. We resolve globs in the defer list using the same concrete path
  // derivation so that pattern equality comparison works on both glob and non-glob inputs.
  const deferList = options?.deferContentPatterns;
  let deferredCount = 0;
  if (deferList && deferList.length > 0 && resolvedRules.fileContentPattern) {
    // Resolve plan doc globs in defer entries so they match resolvedRules paths
    let resolvedDeferList = deferList;
    if (meta.currentStage === "plan") {
      const planDocPath = await resolvePlanDocPath(config, meta);
      if (planDocPath) {
        const relPlanDoc = path.relative(config.projectRoot, planDocPath);
        resolvedDeferList = deferList.map((d) => ({
          ...d,
          path: isPlanDocGlob(d.path) ? relPlanDoc : d.path,
        }));
      }
    }

    const original = resolvedRules.fileContentPattern;
    const filtered = original.filter(
      (r) => !resolvedDeferList.some((d) => d.path === r.path && d.pattern === r.pattern),
    );
    deferredCount = original.length - filtered.length;
    if (deferredCount > 0) {
      resolvedRules = { ...resolvedRules, fileContentPattern: filtered };
      await safeWriteAuditLog("verify_rule_deferred", {
        pipelineId: meta.pipelineId,
        stage: meta.currentStage,
        deferredCount: String(deferredCount),
      }, "info");
    }
  }

  // Detect unresolved {requirementDoc} placeholders (L2-A: explicit failure instead of EISDIR)
  const unresolvedPlaceholder = /\{requirementDoc\}/;
  const unresolvedRuleType =
    (resolvedRules.requiredFiles?.some(p => unresolvedPlaceholder.test(p)) ? "requiredFiles" : null) ??
    (resolvedRules.fileContentPattern?.some(r => unresolvedPlaceholder.test(r.path)) ? "fileContentPattern" : null);
  if (unresolvedRuleType) {
    const structuredResult: StructuredVerifyResult = {
      passed: false,
      failures: [{
        ruleType: unresolvedRuleType,
        // Phase 4 (Bug 4-A): append remediation hint — run /pipeline-start with doc_file
        detail: `requirementDoc not set, cannot resolve {requirementDoc} verify rule path. Run /pipeline-start <doc_file> to set requirementDoc`,
      }],
    };
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };
    return {
      rulePassed: false,
      ruleMissing: [],
      needsModelVerify: true,
      modelPrompt: effectivePrompt,
      structuredResult,
      verifyResult,
    };
  }

  // Check if any structured (non-keyword) rules are defined
  const hasStructuredRules =
    (resolvedRules.requiredFiles && resolvedRules.requiredFiles.length > 0) ||
    (resolvedRules.requiredCommands && resolvedRules.requiredCommands.length > 0) ||
    !!resolvedRules.requiredGit ||
    (resolvedRules.fileContentPattern && resolvedRules.fileContentPattern.length > 0);

  if (hasStructuredRules) {
    // Phase 6 (139): merge VERIFIED_COMMANDS from task result text with toolCallRecords
    const verifiedCmds = parseVerifiedCommands(assistantMessages);
    const mergedRecords = [
      ...(options?.toolCallRecords ?? []),
      ...verifiedCmds,
    ];

    // Use the structured rule engine
    structuredResult = await executeStructuredRules(
      resolvedRules,
      config.projectRoot,
      assistantMessages,
      options?.execFn,
      logError,
      mergedRecords.length > 0 ? mergedRecords : undefined,
      verifyConfig.selfVerifySkip === true,
      meta.stageStartTime,
      meta.currentStage,
    );
  } else {
    // Legacy path: keyword-only rules
    const ruleResult = ruleVerify(resolvedRules, assistantMessages);
    if (!ruleResult.passed) {
      structuredResult = {
        passed: false,
        failures: [{ ruleType: "keywords", detail: `Missing keywords: ${ruleResult.missing.join(", ")}` }],
      };
    }
  }

  // Combine results: structured-only path (Q6-B: LLM layer removed)
  const overallPassed = structuredResult.passed;
  const verifyResult: VerifyResult = { structured: structuredResult, overallPassed };

  if (overallPassed) {
    return {
      rulePassed: true,
      ruleMissing: [],
      needsModelVerify: false,
      modelPrompt: "",
      structuredResult,
      verifyResult,
    };
  }

  // Collect missing keyword info for backward compat
  const keywordFailures = structuredResult.failures.filter(f => f.ruleType === "keywords");
  const ruleMissing = keywordFailures.length > 0
    ? resolvedRules.keywords.filter(kw => !assistantMessages.join("\n").includes(kw))
    : [];

  return {
    rulePassed: false,
    ruleMissing,
    needsModelVerify: true,
    modelPrompt: effectivePrompt,
    structuredResult,
    verifyResult,
  };
}

/**
 * P1: Pre-check required files before running full verification.
 * Returns early if requiredFiles are not yet produced, avoiding
 * false-negative verification failures and freeze triggers.
 *
 * @param config - Pipeline configuration
 * @param meta - Current session metadata
 * @returns Object with passed flag and missing file list
 */
export async function precheckRequiredFiles(
  config: PipelineConfig,
  meta: SessionMeta,
): Promise<{ passed: boolean; missing: string[] }> {
  const stageConfig = config.stages[meta.currentStage];
  const verifyConfig = stageConfig.verify;

  // No verify config or verify not required → precheck passes
  if (!verifyConfig || !verifyConfig.require) {
    return { passed: true, missing: [] };
  }

  const verifyFile = verifyConfig.verifyFile;
  const verifyPath = verifyFile
    ? (path.isAbsolute(verifyFile)
      ? verifyFile
      : path.join(config.projectRoot, verifyFile))
    : path.join(config.projectRoot, resolveStagePath(DEFAULT_VERIFY_FILE, meta.currentStage));

  // Parse verify.md to extract requiredFiles rules
  const { rules } = await parseVerifyFile(verifyPath);

  // No rules or no requiredFiles → precheck passes
  if (!rules || !rules.requiredFiles || rules.requiredFiles.length === 0) {
    return { passed: true, missing: [] };
  }

  // Resolve {requirementDoc} placeholders before checking files
  // This ensures precheck behavior is consistent with runVerification
  let resolvedRules = resolvePlaceholders(rules, meta);

  // Replace plan doc glob with concrete path (only for plan stage)
  resolvedRules = await applyConcreteStageDocPaths(resolvedRules, config, meta);
  
  // Safety check: resolvePlaceholders preserves requiredFiles array structure
  if (!resolvedRules.requiredFiles || resolvedRules.requiredFiles.length === 0) {
    return { passed: true, missing: [] };
  }

  // Check if required files exist
  const result = await verifyRequiredFiles(resolvedRules.requiredFiles, config.projectRoot);

  if (result.passed) {
    return { passed: true, missing: [] };
  }

  // Extract missing files from detail message
  // verifyRequiredFiles returns detail like "Missing files: file1, file2"
  const missingMatch = result.detail.match(/Missing files:\s*(.+)/);
  const missing = missingMatch
    ? missingMatch[1].split(",").map(s => s.trim())
    : resolvedRules.requiredFiles;

  return { passed: false, missing };
}

/**
 * Prechecks whether the interactive completion marker has been written
 * to the requirement document. Returns true if the marker is found.
 *
 * Returns false (treated as "not yet complete") when:
 * - requirementDoc is not set in session meta
 * - The file cannot be read (missing, permission error, etc.)
 * - The marker string is not found in the file content
 *
 * @param meta - Current session metadata
 * @param marker - The completion marker text to search for
 * @param projectRoot - Project root for resolving relative requirementDoc paths
 */
export async function precheckCompletionMarker(
  meta: SessionMeta,
  marker: string,
  projectRoot: string,
): Promise<boolean> {
  if (!meta.requirementDoc) {
    return false;
  }

  const docPath = path.isAbsolute(meta.requirementDoc)
    ? meta.requirementDoc
    : path.join(projectRoot, meta.requirementDoc);

  try {
    const content = await fs.readFile(docPath, "utf-8");
    return content.includes(marker);
  } catch {
    return false;
  }
}

