/**
 * @module auto-verifier
 * Rule-based + model-based auto-verification engine.
 * Reads verify.md (YAML frontmatter rules + Markdown body prompt) and
 * checks whether the agent's stage output meets verification criteria.
 */

import fs from "node:fs/promises";
import path from "node:path";
import type { PipelineConfig, PipelineStage, SessionMeta, ExecFn, AuditLogFn } from "../types";
import { DEFAULT_VERIFY_PROMPT, DEFAULT_VERIFY_PARSE_PROMPT, DEFAULT_VERIFY_JUDGE_PROMPT, DEFAULT_VERIFY_FILE, resolveStagePath } from "../constants";
import { verifyRequiredFiles, verifyFileContentPattern } from "./verifiers/file-verifier";
import { verifyRequiredCommands } from "./verifiers/command-verifier";
import { verifyRequiredGit } from "./verifiers/git-verifier";
import { verifyRequiredKeywords } from "./verifiers/keyword-verifier";
import { safeWriteAuditLog } from "../utils/auditLog";
import { getVerifyPrompt } from "./prompt-config";

/**
 * Parsed verification rules from a verify.md frontmatter.
 * Supports both legacy keyword rules and new structured rule types.
 */
export interface VerifyRules {
  keywords: string[];
  /** "and" = all keywords must match, "or" = any keyword match passes */
  mode: "and" | "or";
  /** File paths that must exist (relative to projectRoot) */
  requiredFiles?: string[];
  /** Shell commands with expected exit codes and output patterns */
  requiredCommands?: RequiredCommand[];
  /** Git repository state checks */
  requiredGit?: RequiredGitRules;
  /** File content regex pattern checks */
  fileContentPattern?: FileContentRule[];
}

/**
 * A shell command verification rule.
 */
export interface RequiredCommand {
  /** The command to execute */
  cmd: string;
  /** Expected exit code (default: 0) */
  expectExit?: number;
  /** Expected substring in stdout */
  expectOutput?: string;
}

/**
 * Git repository state verification rules.
 */
export interface RequiredGitRules {
  /** Time window for last commit (e.g., "10min", "1h") */
  lastCommitWithin?: string;
  /** Expected current branch name */
  branch?: string;
  /** Whether the working tree must be clean */
  cleanWorkingTree?: boolean;
}

/**
 * A file content regex pattern verification rule.
 */
export interface FileContentRule {
  /** File path to check (relative to projectRoot) */
  path: string;
  /** Regex pattern to match against file content */
  pattern: string;
}

/**
 * A structured verification instruction generated by LLM parsing
 * of Markdown body content in verify.md.
 */
export interface VerificationInstruction {
  /** Type of check to perform */
  checkType: "fileExists" | "fileContent" | "command" | "gitStatus";
  /** Target of the check (file path, command, etc.) */
  target: string;
  /** Expected result (optional, depends on checkType) */
  expected?: string;
}

/**
 * Result of structured rule engine verification (Phase 1).
 */
export interface StructuredVerifyResult {
  /** Whether all structured rules passed */
  passed: boolean;
  /** List of failures with rule type and detail */
  failures: VerifyFailure[];
}

/**
 * A single rule failure detail.
 */
export interface VerifyFailure {
  /** The type of rule that failed (e.g., "requiredFiles", "requiredCommands") */
  ruleType: string;
  /** Human-readable failure detail */
  detail: string;
}

/**
 * Unified verification result from structured rules.
 * LLM verification layer removed (Q6-B) — agent-native structured verification only.
 */
export interface VerifyResult {
  /** Result from the structured rule engine */
  structured: StructuredVerifyResult;
  /** Combined overall pass: structured.passed */
  overallPassed: boolean;
}

/**
 * Result of parsing a verify.md file.
 */
export interface ParsedVerifyFile {
  /** Verification rules (null if no YAML frontmatter with keywords) */
  rules: VerifyRules | null;
  /** Model verification prompt (Markdown body or default) */
  prompt: string;
}

/**
 * Parses a verify.md file into rules and a verification prompt.
 * Expects YAML frontmatter (between --- delimiters) for keyword rules,
 * and Markdown body as the model verification prompt.
 */
export async function parseVerifyFile(
  verifyPath: string,
): Promise<ParsedVerifyFile> {
  let raw: string;
  try {
    raw = await fs.readFile(verifyPath, "utf-8");
  } catch {
    return { rules: null, prompt: DEFAULT_VERIFY_PROMPT };
  }

  const parts = raw.split(/^---\s*$/m);
  if (parts.length < 2) {
    return { rules: null, prompt: raw.trim() || DEFAULT_VERIFY_PROMPT };
  }

  // parts[0] is before first --- (should be empty/whitespace)
  // parts[1] is the YAML frontmatter content
  // parts.slice(2).join("---") is the Markdown body
  const frontmatter = parts[1].trim();
  const body = parts.slice(2).join("---").trim();

  const rules = await parseFrontmatter(frontmatter);
  const prompt = body || DEFAULT_VERIFY_PROMPT;

  return { rules, prompt };
}

/**
 * Strips surrounding YAML quotes and unescapes double-quoted content.
 * - Double-quoted: unescapes YAML escape sequences (\\, \", \n, \t, \r, \/, \b, \f, \uXXXX)
 * - Single-quoted: unescapes YAML single-quote doubling ('' → ')
 * - Unquoted: returned as-is
 */
function stripYamlQuotes(raw: string): string {
  const trimmed = raw.trim();
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return unescapeYamlString(trimmed.slice(1, -1));
  }
  if (trimmed.length >= 2 && trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1).replace(/''/g, "'");
  }
  return trimmed;
}

/**
 * Unescapes a YAML double-quoted string scalar (content between the outer quotes).
 * Handles: \\\\ → \\, \\" → ", \\n → newline, \\t → tab, \\r → CR,
 * \\/ → /, \\b → backspace, \\f → form-feed, \\uXXXX → unicode char.
 * Unknown escape sequences preserve both characters per YAML spec.
 */
function unescapeYamlString(s: string): string {
  let result = "";
  let i = 0;
  while (i < s.length) {
    if (s[i] === "\\" && i + 1 < s.length) {
      const next = s[i + 1];
      switch (next) {
        case "\\": result += "\\"; i += 2; break;
        case "\"": result += "\""; i += 2; break;
        case "n": result += "\n"; i += 2; break;
        case "t": result += "\t"; i += 2; break;
        case "r": result += "\r"; i += 2; break;
        case "/": result += "/"; i += 2; break;
        case "b": result += "\b"; i += 2; break;
        case "f": result += "\f"; i += 2; break;
        case "u": {
          if (i + 5 < s.length) {
            const hex = s.substring(i + 2, i + 6);
            if (/^[0-9a-fA-F]{4}$/.test(hex)) {
              result += String.fromCharCode(parseInt(hex, 16));
              i += 6;
              break;
            }
          }
          result += s[i]; i++; break;
        }
        default:
          result += s[i]; i++; break;
      }
    } else {
      result += s[i]; i++;
    }
  }
  return result;
}

/**
 * Parses YAML like frontmatter content into VerifyRules.
 * Uses a simple key-value parser — no full YAML library dependency.
 * Supports: keywords, mode, requiredFiles, requiredCommands, requiredGit, fileContentPattern.
 */
export async function parseFrontmatter(yaml: string): Promise<VerifyRules | null> {
  try {
    const lines = yaml.split("\n");
    const keywords: string[] = [];
    let mode: "and" | "or" = "or";
    const requiredFiles: string[] = [];
    const requiredCommands: RequiredCommand[] = [];
    const fileContentPattern: FileContentRule[] = [];
    let requiredGit: RequiredGitRules | undefined;

    // Section tracking state (indent-aware: P2 fix)
    type Section = "none" | "keywords" | "requiredFiles" | "requiredCommands" | "requiredGit" | "fileContentPattern" | "cmdItem" | "fcItem";
    let currentSection: Section = "none";
    let sectionIndent = 0;
    let currentCmd: RequiredCommand | null = null;
    let currentFc: FileContentRule | null = null;

    for (const line of lines) {
      const trimmed = line.trim();
      const indent = line.length - line.trimStart().length;

      // Skip empty lines
      if (!trimmed) continue;

      // Top-level rules: key
      if (trimmed.startsWith("rules:") && indent === 0) {
        continue;
      }

      // Detect section starts by key prefix (P2 fix: indent-aware, no absolute indent check)
      // Flush any pending cmdItem/fcItem before switching section to prevent
      // silent data loss when a section key immediately follows the last item
      // (e.g., requiredCommands → keywords in generator output).
      if (
        trimmed.startsWith("keywords:") ||
        trimmed.startsWith("mode:") ||
        trimmed.startsWith("requiredFiles:") ||
        trimmed.startsWith("requiredCommands:") ||
        trimmed.startsWith("requiredGit:") ||
        trimmed.startsWith("fileContentPattern:")
      ) {
        if (currentSection === "cmdItem" && currentCmd) {
          requiredCommands.push({ ...currentCmd });
          currentCmd = null;
        }
        if (currentSection === "fcItem" && currentFc) {
          fileContentPattern.push({ ...currentFc });
          currentFc = null;
        }
      }

      if (trimmed.startsWith("keywords:")) {
        currentSection = "keywords";
        sectionIndent = indent;
        continue;
      }
      if (trimmed.startsWith("mode:")) {
        const value = trimmed.split(":")[1]?.trim();
        const modeVal = stripYamlQuotes(value);
        if (modeVal === "and" || modeVal === "or") mode = modeVal;
        currentSection = "none";
        continue;
      }
      if (trimmed.startsWith("requiredFiles:")) {
        currentSection = "requiredFiles";
        sectionIndent = indent;
        continue;
      }
      if (trimmed.startsWith("requiredCommands:")) {
        currentSection = "requiredCommands";
        sectionIndent = indent;
        continue;
      }
      if (trimmed.startsWith("requiredGit:")) {
        currentSection = "requiredGit";
        sectionIndent = indent;
        requiredGit = {};
        continue;
      }
      if (trimmed.startsWith("fileContentPattern:")) {
        currentSection = "fileContentPattern";
        sectionIndent = indent;
        continue;
      }

      // List items for simple string arrays
      if (trimmed.startsWith("- ")) {
        // Flush previous object items when starting a new list entry
        if (currentSection === "cmdItem" && currentCmd) {
          requiredCommands.push({ ...currentCmd });
          currentCmd = null;
        }
        if (currentSection === "fcItem" && currentFc) {
          fileContentPattern.push({ ...currentFc });
          currentFc = null;
        }

        if (currentSection === "keywords" || currentSection === "cmdItem") {
          if (currentSection === "keywords") {
            const kw = stripYamlQuotes(trimmed.slice(2));
            if (kw) keywords.push(kw);
            continue; // P1 fix: prevent trailing reset from clearing currentSection
          } else {
            // We were in cmdItem and got flushed above — switch to requiredCommands
            currentSection = "requiredCommands";
          }
        }
        if (currentSection === "requiredFiles") {
          const fp = stripYamlQuotes(trimmed.slice(2));
          if (fp) requiredFiles.push(fp);
          continue;
        }
        if (currentSection === "requiredCommands") {
          // Start a new command object — "- cmd: ..." or "- \"command\""
          currentCmd = { cmd: "" };
          currentSection = "cmdItem";
          const afterDash = trimmed.slice(2).trim();
          if (afterDash.startsWith("cmd:")) {
            currentCmd.cmd = stripYamlQuotes(afterDash.slice(4));
          } else if (afterDash) {
            currentCmd.cmd = stripYamlQuotes(afterDash);
          }
          continue;
        }
        if (currentSection === "fileContentPattern" || currentSection === "fcItem") {
          if (currentSection === "fcItem") {
            // Already flushed above — switch to fileContentPattern
            currentSection = "fileContentPattern";
          }
          // Start a new fileContentRule object — "- path: ..."
          currentFc = { path: "", pattern: "" };
          currentSection = "fcItem";
          const afterDash = trimmed.slice(2).trim();
          if (afterDash.startsWith("path:")) {
            currentFc.path = stripYamlQuotes(afterDash.slice(5));
          }
          continue;
        }
      }

      // Properties within a command item (4+ indent)
      if (currentSection === "cmdItem" && currentCmd) {
        if (trimmed.startsWith("cmd:")) {
          currentCmd.cmd = stripYamlQuotes(trimmed.slice(4));
        } else if (trimmed.startsWith("expectExit:")) {
          const val = trimmed.split(":")[1]?.trim();
          const num = parseInt(val, 10);
          if (!isNaN(num)) currentCmd.expectExit = num;
        } else if (trimmed.startsWith("expectOutput:")) {
          currentCmd.expectOutput = stripYamlQuotes(trimmed.slice(13));
        } else if (indent <= 2) {
          // New top-level section — save and exit
          requiredCommands.push({ ...currentCmd });
          currentCmd = null;
          currentSection = "none";
        }
        continue;
      }

      // Properties within a fileContentPattern item (4+ indent)
      if (currentSection === "fcItem" && currentFc) {
        if (trimmed.startsWith("path:")) {
          currentFc.path = stripYamlQuotes(trimmed.slice(5));
        } else if (trimmed.startsWith("pattern:")) {
          currentFc.pattern = stripYamlQuotes(trimmed.slice(8));
        } else if (indent <= 2) {
          fileContentPattern.push({ ...currentFc });
          currentFc = null;
          currentSection = "none";
        }
        continue;
      }

      // Properties within requiredGit (2+ indent)
      if (currentSection === "requiredGit" && requiredGit) {
        if (trimmed.startsWith("lastCommitWithin:")) {
          requiredGit.lastCommitWithin = stripYamlQuotes(trimmed.slice(18));
        } else if (trimmed.startsWith("branch:")) {
          requiredGit.branch = stripYamlQuotes(trimmed.slice(7));
        } else if (trimmed.startsWith("cleanWorkingTree:")) {
          const val = trimmed.split(":")[1]?.trim().toLowerCase();
          requiredGit.cleanWorkingTree = val === "true";
        } else if (indent === 0) {
          currentSection = "none";
        }
        continue;
      }

      // Non-matching line at low indent resets section (P2: relative to sectionIndent)
      if (indent <= sectionIndent) {
        // Flush pending items
        if (currentSection === "cmdItem" && currentCmd) {
          requiredCommands.push({ ...currentCmd });
          currentCmd = null;
        }
        if (currentSection === "fcItem" && currentFc) {
          fileContentPattern.push({ ...currentFc });
          currentFc = null;
        }
        currentSection = "none";
      }
    }

    // Flush any pending items at end of file
    if (currentSection === "cmdItem" && currentCmd) {
      requiredCommands.push({ ...currentCmd });
    }
    if (currentSection === "fcItem" && currentFc) {
      fileContentPattern.push({ ...currentFc });
    }

    // Empty-item validation: discard entries with blank path/pattern/keyword
    const emptyItems: string[] = [];
    const filteredKeywords = keywords.filter(kw => {
      const valid = kw.trim() !== "";
      if (!valid) emptyItems.push(`keywords: "${kw}"`);
      return valid;
    });
    const filteredRequiredFiles = requiredFiles.filter(fp => {
      const valid = fp.trim() !== "";
      if (!valid) emptyItems.push(`requiredFiles: "${fp}"`);
      return valid;
    });
    const filteredFileContentPattern = fileContentPattern.filter(rule => {
      const pathValid = rule.path.trim() !== "";
      const patternValid = rule.pattern.trim() !== "";
      if (!pathValid) emptyItems.push(`fileContentPattern missing path`);
      if (!patternValid) emptyItems.push(`fileContentPattern missing pattern (path="${rule.path}")`);
      return pathValid && patternValid;
    });
    if (emptyItems.length > 0) {
      await safeWriteAuditLog("verify_frontmatter_parse_error", {
        error: "Empty entries discarded",
        emptyItems: emptyItems.join("; "),
      });
    }

    // Determine if any rules exist at all
    const hasAnyRules =
      filteredKeywords.length > 0 ||
      filteredRequiredFiles.length > 0 ||
      requiredCommands.length > 0 ||
      !!requiredGit ||
      filteredFileContentPattern.length > 0;

    if (!hasAnyRules) {
      return null;
    }

    return {
      keywords: filteredKeywords,
      mode,
      ...(filteredRequiredFiles.length > 0 ? { requiredFiles: filteredRequiredFiles } : {}),
      ...(requiredCommands.length > 0 ? { requiredCommands } : {}),
      ...(requiredGit ? { requiredGit } : {}),
      ...(filteredFileContentPattern.length > 0 ? { fileContentPattern: filteredFileContentPattern } : {}),
    };
  } catch (err) {
    const errMsg = err instanceof Error ? err.message : String(err);
    await safeWriteAuditLog("verify_frontmatter_parse_error", { error: errMsg }, "error");
    return null;
  }
}

/**
 * Runs rule-based verification against the aggregated assistant messages.
 * Q5 Option C: aggregates ALL assistant messages from the current stage,
 * then checks against keyword rules (AND or OR mode).
 */
export function ruleVerify(
  rules: VerifyRules,
  assistantMessages: string[],
): { passed: boolean; missing: string[] } {
  const aggregated = assistantMessages.join("\n");

  if (rules.mode === "and") {
    const missing = rules.keywords.filter(
      (kw) => !aggregated.includes(kw),
    );
    return { passed: missing.length === 0, missing };
  }

  // mode "or" — any keyword match passes
  const found = rules.keywords.some((kw) => aggregated.includes(kw));
  if (found) {
    return { passed: true, missing: [] };
  }
  return { passed: false, missing: rules.keywords };
}

/**
 * Executes all structured rules from VerifyRules against the filesystem,
 * git state, and assistant messages. Each rule type is evaluated independently.
 *
 * @param rules - The parsed verification rules from verify.md
 * @param projectRoot - Absolute path to the project root directory
 * @param assistantMessages - Aggregated assistant messages for keyword checking
 * @param execFn - Injected shell execution function
 * @param logError - Optional audit log callback for recording errors
 * @param toolCallRecords - Tool call records for selfVerifySkip matching
 * @param selfVerifySkip - Whether selfVerifySkip is enabled for this stage
 * @param stageStartTime - Stage start time for file-change invalidation
 * @returns StructuredVerifyResult with per-rule-type pass/fail and failure details
 */
export async function executeStructuredRules(
  rules: VerifyRules,
  projectRoot: string,
  assistantMessages: string[],
  execFn?: ExecFn,
  logError?: AuditLogFn,
  toolCallRecords?: Array<{ name: string; command?: string; exitCode?: number; success?: boolean; ts: number }>,
  selfVerifySkip?: boolean,
  stageStartTime?: number,
  stageName?: string,
): Promise<StructuredVerifyResult> {
  const failures: VerifyFailure[] = [];

  // 1. Required files check
  const fileResult = await verifyRequiredFiles(rules.requiredFiles, projectRoot);
  if (!fileResult.passed) {
    failures.push({ ruleType: "requiredFiles", detail: fileResult.detail });
  }

  // 2. Required commands check
  const cmdResult = await verifyRequiredCommands(
    rules.requiredCommands,
    projectRoot,
    execFn,
    logError,
    selfVerifySkip === true ? { toolCallRecords, stageStartTime, stageName } : undefined,
  );
  if (!cmdResult.passed) {
    failures.push({ ruleType: "requiredCommands", detail: cmdResult.detail });
  }

  // 3. Required git state check
  const gitResult = await verifyRequiredGit(rules.requiredGit, projectRoot, execFn, logError);
  if (!gitResult.passed) {
    failures.push({ ruleType: "requiredGit", detail: gitResult.detail });
  }

  // 4. File content pattern check
  const fcResult = await verifyFileContentPattern(rules.fileContentPattern, projectRoot, logError);
  if (!fcResult.passed) {
    failures.push({ ruleType: "fileContentPattern", detail: fcResult.detail });
  }

  // 5. Keyword check (legacy)
  if (rules.keywords.length > 0) {
    const kwResult = verifyRequiredKeywords(rules.keywords, rules.mode, assistantMessages);
    if (!kwResult.passed) {
      failures.push({ ruleType: "keywords", detail: kwResult.detail });
    }
  }

  return {
    passed: failures.length === 0,
    failures,
  };
}

/**
 * Options for structured verification within runVerification.
 */
export interface RunVerificationOptions {
  /** Dependency-injected shell execution function (replaces child_process.execSync) */
  execFn?: ExecFn;
  /** Override verify.md path; takes precedence over stage config verifyFile */
  verifyFile?: string;
  /** Optional audit log callback override (defaults to auto-constructed closure from meta.pipelineId) */
  logError?: AuditLogFn;
  /** Tool call records for selfVerifySkip (extracted from session by agent-settled) */
  toolCallRecords?: Array<{ name: string; command?: string; exitCode?: number; success?: boolean; ts: number }>;
}

/**
 * Replaces `{requirementDoc}` placeholders in rule paths with the actual
 * requirement document path from session metadata.
 *
 * When `meta.requirementDoc` is unset (undefined or empty string), placeholders
 * are preserved as-is (not replaced with empty string). This prevents downstream
 * EISDIR errors from `path.join(projectRoot, "")` resolving to the project root.
 *
 * @param rules - Parsed verification rules
 * @param meta - Session metadata (may contain requirementDoc)
 * @returns A new VerifyRules object with placeholders resolved
 */
export function resolvePlaceholders(rules: VerifyRules, meta: SessionMeta): VerifyRules {
  const reqDoc = meta.requirementDoc;
  // When requirementDoc is unset, preserve the placeholder as-is (L2-A fix)
  const replace = (s: string): string =>
    reqDoc ? s.replace(/\{requirementDoc\}/g, reqDoc) : s;

  const resolved: VerifyRules = { ...rules };

  if (resolved.requiredFiles) {
    resolved.requiredFiles = resolved.requiredFiles.map(replace);
  }
  if (resolved.fileContentPattern) {
    resolved.fileContentPattern = resolved.fileContentPattern.map((rule) => ({
      ...rule,
      path: replace(rule.path),
    }));
  }

  return resolved;
}

/**
 * Runs the full verification pipeline for a stage:
 * 1. Parse verify.md
 * 2. Run structured rule verification (if new rule types present) or legacy keyword verification
 * 3. Combine structured results into a unified VerifyResult
 *
 * @param config - Pipeline configuration
 * @param meta - Session metadata
 * @param assistantMessages - Aggregated assistant messages
 * @param options - Optional LLM verification options
 */
export async function runVerification(
  config: PipelineConfig,
  meta: SessionMeta,
  assistantMessages: string[],
  options?: RunVerificationOptions,
): Promise<{
  rulePassed: boolean;
  ruleMissing: string[];
  needsModelVerify: boolean;
  modelPrompt: string;
  structuredResult?: StructuredVerifyResult;
  verifyResult?: VerifyResult;
}> {
  const stageConfig = config.stages[meta.currentStage];
  const verifyConfig = stageConfig.verify;

  if (!verifyConfig || !verifyConfig.require) {
    return {
      rulePassed: true,
      ruleMissing: [],
      needsModelVerify: false,
      modelPrompt: "",
    };
  }

  // Override from options takes precedence over stage config
  const verifyFile = options?.verifyFile ?? verifyConfig.verifyFile;
  const verifyPath = verifyFile
    ? (path.isAbsolute(verifyFile)
      ? verifyFile
      : path.join(config.projectRoot, verifyFile))
    : path.join(config.projectRoot, resolveStagePath(DEFAULT_VERIFY_FILE, meta.currentStage));

  const { rules, prompt } = await parseVerifyFile(verifyPath);

  // Override modelPrompt from yml verify_{stage} when available (D5)
  // Fallback chain: yml verify_{stage} → verify.md body prompt → DEFAULT (via parseVerifyFile)
  const ymlPrompt = await getVerifyPrompt(config.projectRoot, meta.currentStage);
  const effectivePrompt = ymlPrompt ?? prompt;

  // Build audit log closure: injects pipelineId into every error-level audit entry
  const logError: AuditLogFn = options?.logError ??
    ((stage, msg) => safeWriteAuditLog(stage, { pipelineId: meta.pipelineId, ...msg }, "error"));

  // Default structured result when no structured rules exist
  let structuredResult: StructuredVerifyResult = { passed: true, failures: [] };

  if (!rules) {
    // No rules defined — structured-only path, no LLM fallback (Q6-B)
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };

    return {
      rulePassed: false,
      ruleMissing: [],
      needsModelVerify: true,
      modelPrompt: effectivePrompt,
      verifyResult,
    };
  }

  // Resolve {requirementDoc} placeholders in rule paths using session metadata
  const resolvedRules = resolvePlaceholders(rules, meta);

  // Detect unresolved {requirementDoc} placeholders (L2-A: explicit failure instead of EISDIR)
  const unresolvedPlaceholder = /\{requirementDoc\}/;
  const unresolvedRuleType =
    (resolvedRules.requiredFiles?.some(p => unresolvedPlaceholder.test(p)) ? "requiredFiles" : null) ??
    (resolvedRules.fileContentPattern?.some(r => unresolvedPlaceholder.test(r.path)) ? "fileContentPattern" : null);
  if (unresolvedRuleType) {
    const structuredResult: StructuredVerifyResult = {
      passed: false,
      failures: [{
        ruleType: unresolvedRuleType,
        detail: `requirementDoc not set, cannot resolve {requirementDoc} verify rule path`,
      }],
    };
    const verifyResult: VerifyResult = { structured: structuredResult, overallPassed: false };
    return {
      rulePassed: false,
      ruleMissing: [],
      needsModelVerify: true,
      modelPrompt: effectivePrompt,
      structuredResult,
      verifyResult,
    };
  }

  // Check if any structured (non-keyword) rules are defined
  const hasStructuredRules =
    (resolvedRules.requiredFiles && resolvedRules.requiredFiles.length > 0) ||
    (resolvedRules.requiredCommands && resolvedRules.requiredCommands.length > 0) ||
    !!resolvedRules.requiredGit ||
    (resolvedRules.fileContentPattern && resolvedRules.fileContentPattern.length > 0);

  if (hasStructuredRules) {
    // Use the structured rule engine
    structuredResult = await executeStructuredRules(
      resolvedRules,
      config.projectRoot,
      assistantMessages,
      options?.execFn,
      logError,
      options?.toolCallRecords,
      verifyConfig.selfVerifySkip === true,
      meta.stageStartTime,
      meta.currentStage,
    );
  } else {
    // Legacy path: keyword-only rules
    const ruleResult = ruleVerify(resolvedRules, assistantMessages);
    if (!ruleResult.passed) {
      structuredResult = {
        passed: false,
        failures: [{ ruleType: "keywords", detail: `Missing keywords: ${ruleResult.missing.join(", ")}` }],
      };
    }
  }

  // Combine results: structured-only path (Q6-B: LLM layer removed)
  const overallPassed = structuredResult.passed;
  const verifyResult: VerifyResult = { structured: structuredResult, overallPassed };

  if (overallPassed) {
    return {
      rulePassed: true,
      ruleMissing: [],
      needsModelVerify: false,
      modelPrompt: "",
      structuredResult,
      verifyResult,
    };
  }

  // Collect missing keyword info for backward compat
  const keywordFailures = structuredResult.failures.filter(f => f.ruleType === "keywords");
  const ruleMissing = keywordFailures.length > 0
    ? resolvedRules.keywords.filter(kw => !assistantMessages.join("\n").includes(kw))
    : [];

  return {
    rulePassed: false,
    ruleMissing,
    needsModelVerify: true,
    modelPrompt: effectivePrompt,
    structuredResult,
    verifyResult,
  };
}
